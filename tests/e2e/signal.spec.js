import { test, expect } from '../aides/gardes.js';
import { viderBase, aller } from '../aides/saisie.js';
import { genererPeriodes } from '../fixtures/generateur.js';
import { addDays } from '../../public/js/domain/dates.js';

test('signal : carte « Pour info » dans Analyse, Masquer, ligne PSY, rien sur Aujourd\'hui', async ({ page }) => {
  test.setTimeout(90000);
  const base = genererPeriodes({ seed: 3 });
  const fin0 = base[base.length - 1].date;
  const journal = [...base];
  for (let k = 0; k < 4; k++) journal.push({ ...base[0], date: addDays(fin0, k + 1), humeur: 6, sommeilRessenti: 'sommeil:mal', contactHumain: false, reveilsNocturnes: 3 });
  const fin = journal[journal.length - 1].date;
  const [a, m, j] = fin.split('-').map(Number);
  await page.clock.install({ time: new Date(a, m - 1, j, 21, 0) });
  await page.goto('/');
  await viderBase(page);
  await page.evaluate(async (js) => { const r = window.__carnet.repo; for (const e of js) { const { date, ...x } = e; await r.journal.patch(date, x); } }, journal);
  await page.reload();
  await expect(page.locator('main')).not.toContainText(/ressembl/i);
  await page.getByRole('link', { name: 'Analyse' }).click();
  const carte = page.getByRole('region', { name: 'Pour info' });
  await expect(carte).toContainText(/Ces 4 derniers jours ressemblent, surtout par/, { timeout: 20000 });
  await expect(carte).toContainText("C'est une ressemblance dans les chiffres, pas une prévision.");
  await carte.getByRole('button', { name: 'Voir le détail' }).click();
  await expect(carte.getByRole('columnheader', { name: 'Avant ces périodes' })).toBeVisible();
  await aller(page, '#/export-psy');
  await expect(page.getByLabel('Aperçu du texte')).toContainText('- Signal : ces 4 derniers jours ressemblent');
  await aller(page, '#/analyse');
  await page.getByRole('region', { name: 'Pour info' }).getByRole('button', { name: 'Masquer', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Pour info' })).toHaveCount(0);
});
